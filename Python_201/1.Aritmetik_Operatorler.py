sayi1 = 12
sayi2 = 5

print(sayi1 + sayi2) # Addition (Toplama)
print(sayi1 - sayi2) # Substraction (Çıkarma)
print(sayi1 * sayi2) # Multiplication (Çarpma)
print(sayi1 / sayi2) # Division (Bölme)
print(sayi1 % sayi2) # Modulus (Modül - Mod Alma)

sayi1 = 17
